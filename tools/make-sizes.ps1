# Generates js/sizes.js with the pixel size of every image in assets/.
# Run from the repository root after adding or replacing images:
#   powershell -ExecutionPolicy Bypass -File tools/make-sizes.ps1
Add-Type -AssemblyName System.Drawing
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$lines = Get-ChildItem (Join-Path $root 'assets') -Recurse -File -Include *.jpg, *.jpeg, *.png, *.webp, *.gif |
  Sort-Object FullName |
  ForEach-Object {
    $img = [System.Drawing.Image]::FromFile($_.FullName)
    $rel = $_.FullName.Substring($root.Length + 1).Replace('\', '/')
    '  "{0}": [{1}, {2}],' -f $rel, $img.Width, $img.Height
    $img.Dispose()
  }
$out = @(
  '// Generated by tools/make-sizes.ps1 - image sizes in pixels [width, height].'
  '// Used to lay out project pages without jumps and to spot low-resolution images.'
  'window.IMAGE_SIZES = {'
) + $lines + '};'
Set-Content -Path (Join-Path $root 'js\sizes.js') -Value $out -Encoding UTF8
"sizes.js: $($lines.Count) images"
